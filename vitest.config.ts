import { defineConfig } from "vitest/config";
import { fileURLToPath } from "node:url";

export default defineConfig({
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
    },
  },
  test: {
    environment: "node",
    include: ["src/**/*.test.ts", "src/**/*.test.tsx"],
    globals: false,
    /**
     * Живые прогоны (`LIVE_DB=1`) — по одному файлу за раз.
     *
     * Файлы живых проверок делят одну базу, и почти каждый из них либо чистит
     * таблицу целиком, либо сверяет абсолютные суммы по всей таблице
     * («расход на рекламу за месяц равен 17 000»). При параллельном запуске
     * они затирают друг друга: insights стирает операции ровно тогда, когда
     * finance их считает. Три теста падали именно поэтому — на пустом месте,
     * с правдоподобным «ожидали 60 000, получили 83 000», и разбор такого
     * падения каждый раз начинается с подозрения на настоящий баг в деньгах.
     *
     * Обычный прогон (без LIVE_DB) параллелизм сохраняет: там базы нет вовсе.
     */
    fileParallelism: process.env.LIVE_DB !== "1",
  },
});
