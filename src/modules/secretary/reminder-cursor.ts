/**
 * Курсор ближайшего напоминания — в памяти процесса.
 *
 * Зачем. Крон напоминаний ходит в базу каждую минуту, и почти всегда впустую:
 * напоминаний нет, ответ пустой. На обычной базе это ничего не стоит. На Neon
 * стоит: запрос раз в минуту не даёт компьюту простоять пять минут без
 * нагрузки, тот не засыпает никогда и выбирает месячный лимит компьют-часов
 * за две с половиной недели. Лимит общий на аккаунт, и вместе с Business OS
 * остановится всё остальное, что живёт на том же Neon.
 *
 * Как. Держим в памяти время ближайшего срабатывания и ходим в базу только
 * когда оно наступило. Это законно ровно потому, что контейнер один и все
 * записи напоминаний идут через него же: и разговор с Асей, и кнопки Telegram
 * обслуживает этот процесс.
 *
 * Главный инвариант: **курсор обязан быть НЕ ПОЗЖЕ настоящего ближайшего
 * срабатывания.** Ошибка в раннюю сторону стоит одного лишнего запроса,
 * ошибка в позднюю — непришедшего напоминания. Поэтому всякая запись только
 * двигает курсор раньше (`noteReminderDue`), а отмены и переносы на потом
 * игнорируются: они делают курсор пессимистичнее, что безопасно.
 *
 * На случай, если новый путь записи однажды забудут подключить, курсор раз в
 * час всё равно перечитывается из базы. Тогда цена забывчивости — задержка
 * максимум на час, а не потерянное навсегда напоминание.
 */

import { logInfo } from "@/core/observability/logger";

/** Как часто курсор перечитывается из базы независимо от его значения. */
const RESYNC_MS = 60 * 60 * 1000;

/**
 * null — «не знаем, надо спросить базу» (старт процесса).
 * Infinity — «активных напоминаний нет».
 */
let earliestMs: number | null = null;
let lastSyncMs = 0;

/**
 * Минимум из того, что записали ПОКА шёл запрос к базе.
 *
 * Нужен из-за гонки, которая иначе теряет напоминания. Между `SELECT` и
 * присваиванием результата процесс успевает обслужить сообщение Telegram: одна
 * задача уходит в ожидание на `await`, вторая создаёт напоминание и зовёт
 * `noteReminderDue`. База о нём ещё не знала, и её ответ затёр бы новое
 * значение — курсор уехал бы вперёд, а напоминание проспало до часовой
 * пересинхронизации.
 */
let sinceSyncMinMs = Number.POSITIVE_INFINITY;

/**
 * Номер текущего похода в базу.
 *
 * Накопителя мало, когда прогонов ДВА. Планировщик запускает джобу, не дожидаясь
 * предыдущей (`void fireCron(job)` в scripts/start-container.mjs), а накопитель
 * один на процесс. Два наложенных прогона: первый получает ответ, склеивает его
 * с накопителем и обнуляет накопитель; второй приходит со СВОИМ, более старым
 * снимком и видит уже пустой накопитель — и затирает курсор значением из
 * прошлого. Курсор уезжает вперёд, напоминание спит до часовой
 * пересинхронизации, то есть опаздывает на срок до 59 минут.
 *
 * Токен это чинит: ответ применяется, только если с его начала не стартовал
 * следующий поход. Ответ проигравшего отбрасывается целиком — он всё равно
 * старше того, что уже едет.
 */
let syncToken = 0;

/** Идти ли в базу за напоминаниями на этом тике. */
export function shouldCheckReminders(now: Date = new Date()): boolean {
  if (earliestMs === null) return true;
  if (now.getTime() - lastSyncMs >= RESYNC_MS) return true;
  return now.getTime() >= earliestMs;
}

/**
 * Начало похода в базу. Вызывать ПЕРЕД запросом: с этого момента всё, что
 * запишут параллельные задачи, копится отдельно и переживёт ответ базы.
 */
export function beginCursorSync(): number {
  sinceSyncMinMs = Number.POSITIVE_INFINITY;
  syncToken += 1;
  return syncToken;
}

/**
 * База ответила: ближайшее активное напоминание — вот это (или их нет).
 * Вызывается после каждого похода в базу.
 *
 * Берём минимум с тем, что записали во время запроса: ответ базы — снимок
 * прошлого, и он не должен отменять более раннее напоминание, созданное уже
 * после снимка.
 */
export function setEarliestReminder(
  next: Date | null,
  now: Date = new Date(),
  token?: number,
): void {
  // Ответ обогнавшего нас прогона молча выбрасываем: он старше, а накопитель
  // с тех пор уже принадлежит не нам. Применить его — значит затереть курсор
  // прошлым.
  if (token !== undefined && token !== syncToken) return;

  const fromDb = next === null ? Number.POSITIVE_INFINITY : next.getTime();
  earliestMs = Math.min(fromDb, sinceSyncMinMs);
  sinceSyncMinMs = Number.POSITIVE_INFINITY;
  lastSyncMs = now.getTime();
}

/**
 * Отложить следующий поход в базу, ничего о ней не узнав.
 *
 * Нужно после сбоя запроса. Курсор в состоянии «не знаю» заставляет идти в базу
 * каждую минуту — то есть ровно тот поминутный долбёж, ради ухода от которого
 * курсор и заведён, и включается он в самый неподходящий момент: когда база и
 * так не отвечает.
 */
export function backOffCursor(delayMs: number, now: Date = new Date()): void {
  earliestMs = now.getTime() + delayMs;
  lastSyncMs = now.getTime();
  syncToken += 1;
}

/**
 * Появилось или подвинулось напоминание. Курсор берёт минимум — проспать
 * новое напоминание нельзя, а лишний раз проснуться можно.
 *
 * В накопитель пишем ВСЕГДА, даже когда курсор ещё не знает состояния базы:
 * иначе запись, попавшая в самый первый синк, потеряется ровно так же.
 */
export function noteReminderDue(at: Date): void {
  const ms = at.getTime();
  if (ms < sinceSyncMinMs) sinceSyncMinMs = ms;
  if (earliestMs === null) return;
  if (ms < earliestMs) earliestMs = ms;
}

/**
 * Сбросить курсор в «не знаю». Нужен там, где состояние базы могло измениться
 * непредсказуемо и дешевле перечитать, чем рассуждать.
 */
export function invalidateReminderCursor(): void {
  earliestMs = null;
}

/** Диагностика: что курсор думает прямо сейчас. */
export function reminderCursorState(): { earliest: Date | null; knows: boolean } {
  if (earliestMs === null) return { earliest: null, knows: false };
  if (!Number.isFinite(earliestMs)) return { earliest: null, knows: true };
  return { earliest: new Date(earliestMs), knows: true };
}

/** Только для тестов. */
export function resetReminderCursor(): void {
  earliestMs = null;
  lastSyncMs = 0;
  sinceSyncMinMs = Number.POSITIVE_INFINITY;
  syncToken += 1;
}

export function logCursor(event: string): void {
  const state = reminderCursorState();
  logInfo(event, {
    knows: state.knows,
    earliest: state.earliest?.toISOString() ?? "нет активных",
  });
}
