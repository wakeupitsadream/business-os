/**
 * Разбор момента времени, присланного моделью.
 *
 * Модель получает в системном промпте текущее время владельца и его часовой
 * пояс, поэтому переводить «завтра в 10» в дату — её работа, а не наша: свой
 * парсер русских дат пришлось бы бесконечно достраивать («в следующий вторник»,
 * «после обеда», «через пару дней»), и он всё равно проигрывал бы модели.
 *
 * Наша работа — не пустить в базу заведомую чушь. Модель ошибается предсказуемо:
 * присылает время в прошлом (посчитала от даты обучения), теряет часовой пояс
 * (тогда строка читается как UTC и напоминание уезжает на три часа) или уносит
 * дату на годы вперёд.
 */

/** Дальше этого срока напоминание почти наверняка означает ошибку модели. */
const MAX_YEARS_AHEAD = 5;

/**
 * Допуск на прошлое. Пока модель думает и инструмент исполняется, проходят
 * секунды; «через минуту» не должно отвергаться из-за этого.
 */
const PAST_TOLERANCE_MS = 2 * 60 * 1000;

export type WhenResult = { ok: true; date: Date } | { ok: false; error: string };

export function parseWhen(raw: string, now: Date): WhenResult {
  const text = raw.trim();
  if (text.length === 0) return { ok: false, error: "время не указано" };

  const date = new Date(text);
  if (Number.isNaN(date.getTime())) {
    return {
      ok: false,
      error:
        `не удалось разобрать время «${text}». Пришли его в формате ISO 8601 ` +
        "с часовым поясом, например 2026-07-30T10:00:00+03:00",
    };
  }

  if (!hasExplicitZone(text)) {
    // Без пояса строка трактуется как UTC — напоминание уехало бы на три часа,
    // и владелец получил бы его в 07:00 вместо 10:00, не понимая почему.
    return {
      ok: false,
      error:
        `во времени «${text}» не указан часовой пояс. Добавь смещение владельца, ` +
        "например 2026-07-30T10:00:00+03:00",
    };
  }

  if (date.getTime() < now.getTime() - PAST_TOLERANCE_MS) {
    return {
      ok: false,
      error:
        `время ${text} уже прошло. Проверь текущую дату из системного промпта ` +
        "и посчитай заново",
    };
  }

  const limit = new Date(now);
  limit.setFullYear(limit.getFullYear() + MAX_YEARS_AHEAD);
  if (date.getTime() > limit.getTime()) {
    return { ok: false, error: `время ${text} слишком далеко в будущем — похоже на ошибку` };
  }

  return { ok: true, date };
}

/**
 * Есть ли в строке явный часовой пояс: «Z» или смещение вида ±HH:MM в
 * ВРЕМЕННОЙ части. Проверять просто наличие «+» нельзя — в дате есть дефисы,
 * а «-» встречается и как разделитель, поэтому смотрим на хвост после «T».
 */
function hasExplicitZone(text: string): boolean {
  const timePart = text.includes("T") ? text.slice(text.indexOf("T") + 1) : "";
  if (timePart.length === 0) return false;
  return /[zZ]$/.test(timePart) || /[+-]\d{2}:?\d{2}$/.test(timePart);
}
