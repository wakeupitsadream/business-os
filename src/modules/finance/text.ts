/**
 * Разбор русского текста для подбора категории.
 *
 * Владелец диктует расход живой речью: «потратил 3500 на бензин», «ушло
 * 12к на рекламу». Алиасы в справочнике записаны в начальной форме
 * («бензин», «реклама»), а в тексте стоят падежи («бензина», «рекламу»).
 * Сравнение строк «как есть» промахивается на большинстве фраз, поэтому
 * перед сравнением слова приводятся к грубой основе.
 *
 * Это НЕ морфологический анализатор. Полноценный (mystem, pymorphy) сюда не
 * поставить — нет ни зависимости под Node, ни причины тащить её ради двух
 * десятков категорий. Отсечение окончаний ошибается, но ошибается в понятную
 * сторону, а цена ошибки мала: не подобралась категория — уходим к дешёвой
 * модели, подобралась не та — владелец видит её в ответе и поправляет.
 */

/**
 * Окончания, отсекаемые с конца слова. Порядок важен: сначала длинные, иначе
 * «домами» превратилось бы в «домам», а не в «дом».
 */
const ENDINGS = [
  "иями",
  "ями",
  "ами",
  "ого",
  "его",
  "ому",
  "ему",
  "ыми",
  "ими",
  "ах",
  "ях",
  "ов",
  "ев",
  "ой",
  "ей",
  "ую",
  "юю",
  "ом",
  "ем",
  "ий",
  "ый",
  "ая",
  "яя",
  "ое",
  "ее",
  "ы",
  "и",
  "а",
  "я",
  "у",
  "ю",
  "е",
  "о",
  "ь",
  "й",
];

/**
 * Пороги подобраны по реальному списку алиасов, а не «на глаз».
 *
 * Планка в четыре буквы выглядела бы аккуратнее, но тогда «на еду» перестаёт
 * находить категорию «Питание»: «еда» и «еду» — три буквы. Ценой служит редкий
 * ложный сработ («еду на такси» даёт и «Питание», и «Транспорт»), и он
 * разрешается предпочтением более длинного алиаса — «такси» побеждает «еду».
 */
const MIN_WORD_LENGTH = 3;
/** Что должно остаться после отсечения, иначе окончание не то. */
const MIN_STEM_LENGTH = 2;

/**
 * Нормализация: регистр, ё→е, всё кроме букв и цифр — в пробелы.
 * Цифры сохраняем: «300к» отличается от «300».
 */
export function normalizeText(input: string): string {
  return input
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

export function tokenize(input: string): string[] {
  const normalized = normalizeText(input);
  return normalized.length === 0 ? [] : normalized.split(" ");
}

/** Грубая основа слова: отсечение одного окончания из списка. */
export function stem(word: string): string {
  const w = normalizeText(word);
  if (w.length < MIN_WORD_LENGTH) return w;

  for (const ending of ENDINGS) {
    if (w.length - ending.length >= MIN_STEM_LENGTH && w.endsWith(ending)) {
      return w.slice(0, w.length - ending.length);
    }
  }
  return w;
}

export function stemAll(input: string): string[] {
  return tokenize(input).map(stem);
}

/**
 * Встречается ли фраза (одно или несколько слов) в тексте — по основам и
 * подряд идущим словам.
 *
 * Именно подряд: «яндекс директ» не должно срабатывать на «яндекс такси и
 * директ-маркетинг в одном чеке» — там это два разных расхода, и склеивать
 * их в одну категорию хуже, чем не угадать вовсе.
 */
export function phraseOccurs(phrase: string, textStems: string[]): boolean {
  const needle = stemAll(phrase);
  if (needle.length === 0 || needle.length > textStems.length) return false;

  outer: for (let i = 0; i + needle.length <= textStems.length; i += 1) {
    for (let j = 0; j < needle.length; j += 1) {
      if (textStems[i + j] !== needle[j]) continue outer;
    }
    return true;
  }
  return false;
}
