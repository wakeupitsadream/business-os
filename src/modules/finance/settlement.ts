import { normalizeText } from "./text";

/**
 * Вывод эквайринга: распознавание и правило «доход это или перемещение».
 *
 * Задача. Выручка Agentus приходит на счёт ЮKassa, синк записывает её как
 * доход на `acc_yookassa`. Раз в несколько дней ЮKassa переводит накопленное на
 * расчётный счёт, и этот перевод попадает в банковскую выписку отдельной
 * приходной строкой. Импорт до сих пор засчитывал её ВТОРЫМ доходом — те же
 * деньги учитывались дважды, причём незаметно: две строки лежат на разных
 * счетах, с разными суммами и датами, и сойтись с кабинетом ЮKassa месячная
 * выручка не могла в принципе.
 *
 * Комментарий в миграции `00000000000007` обещал, что вывод «опознается
 * импортом как перевод между своими счетами — механизм уже написан». Обещание
 * неверное: `findTransfer` ищет встречную ногу среди уже записанных операций, а
 * исходящей ноги на `acc_yookassa` не пишет никто (синк забирает только
 * `/v3/payments`). Плюс сумма вывода — это сумма многих платежей за вычетом
 * комиссий, она не совпадёт ни с одним отдельным платежом, а `findTransfer`
 * сверяет суммы точным равенством.
 *
 * **Почему одного распознавания по тексту мало.** Если синк ЮKassa не настроен
 * (сегодняшнее состояние системы) или выписка старше окна холодного старта, то
 * приходная строка в банке — ЕДИНСТВЕННАЯ запись об этой выручке. Молча
 * превратить её в перемещение значит обнулить месячную выручку: недоучёт хуже
 * переучёта, потому что заметить нечем — второй строки просто нет.
 *
 * Поэтому решает не текст, а ДЕНЬГИ: строка считается выводом только тогда,
 * когда на счёте ЮKassa действительно лежит невыведенная выручка, которой
 * хватает на эту сумму. Текст лишь называет кандидата.
 */

/**
 * Признаки вывода в назначении платежа.
 *
 * Обе раскладки намеренно: в выписках встречается и «ЮKassa» (кириллическая Ю
 * с латинским KASSA), и целиком кириллическое «ЮКАССА». Сравнение идёт по
 * `normalizeText`, то есть в нижнем регистре и без знаков препинания.
 */
const SETTLEMENT_HINTS = [
  "юkassa",
  "юкасса",
  "yookassa",
  "yoomoney",
  "юmoney",
  "юмани",
];

/**
 * Голого «эквайринг» в списке НЕТ намеренно.
 *
 * Владелец может держать второй эквайринг (Т-Банк, Robokassa), и его выплата
 * приходит строкой вида «Зачисление по операциям эквайринга» — без единого
 * упоминания ЮKassa. По голой подстроке она стала бы переводом со счёта
 * ЮKassa: чужая выручка исчезла бы из доходов, а виртуальный счёт ушёл бы в
 * минус. Промах в другую сторону дешевле: строка остаётся доходом, то есть
 * поведение ровно то же, что было до этой правки.
 */

/** Похоже ли назначение платежа на вывод эквайринга. */
export function looksLikeSettlement(description: string): boolean {
  const text = normalizeText(description);
  return SETTLEMENT_HINTS.some((hint) => text.includes(normalizeText(hint)));
}

export type SettlementVerdict =
  | { kind: "settlement" }
  /** Похоже на вывод, но подтверждённой выручки на счёте ЮKassa не хватает. */
  | { kind: "uncovered"; availableKop: number }
  | { kind: "no" };

/**
 * Решение по одной строке.
 *
 * `availableKop` — сколько невыведенной выручки числится на счёте ЮKassa на
 * момент разбора этой строки. Вызывающий уменьшает его сам по мере того, как
 * строки файла разбирают этот остаток: две выплаты в одной выписке не должны
 * обе опереться на один и тот же запас.
 */
export function classifySettlement(row: {
  type: "INCOME" | "EXPENSE";
  description: string;
  amountKop: number;
  availableKop: number;
  /** Счёт, чья выписка импортируется. */
  statementAccountId: string;
  yookassaAccountId: string;
}): SettlementVerdict {
  // Вывод — это всегда приход на банковский счёт. Расход с таким текстом —
  // это комиссия, её пишет синк, и трогать её здесь нечего.
  if (row.type !== "INCOME") return { kind: "no" };
  // Выписка самого счёта ЮKassa: переворачивать нечего.
  if (row.statementAccountId === row.yookassaAccountId) return { kind: "no" };
  if (!looksLikeSettlement(row.description)) return { kind: "no" };

  if (row.availableKop < row.amountKop) {
    return { kind: "uncovered", availableKop: row.availableKop };
  }
  return { kind: "settlement" };
}
