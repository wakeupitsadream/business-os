/**
 * Нормализация телефона — первый и самый надёжный уровень дедупа лидов.
 *
 * Один и тот же автосервис приезжает из Яндекса, из 2ГИС и из заявки на сайте
 * под тремя разными названиями («Автосервис на Ленина», «ИП Кузнецов А.А.»,
 * «АвтоЛидер») и в трёх разных написаниях номера. Совпадает только номер, и
 * именно поэтому `Lead.phoneNormalized` уникален.
 *
 * Канон — 11 цифр, начиная с 7: `79991234567`. Российский номер записывают
 * шестью способами (+7, 8, 7, со скобками, с дефисами, с пробелами), и любые
 * два из них обязаны дать одну строку. Иначе уникальный индекс не сработает и
 * дедуп превращается в украшение.
 */

/** Сколько цифр в российском номере вместе с кодом страны. */
const RU_LENGTH = 11;

/**
 * Номер в каноническом виде или `null`, если это не похоже на телефон.
 *
 * `null` — полноценный результат, а не ошибка: у входящей заявки с сайта
 * телефона может не быть вовсе, и это нормально. Возвращать при этом мусор
 * («8», «+7») было бы хуже — такой «номер» занял бы уникальный индекс и
 * склеил бы двух разных лидов в одного.
 */
export function normalizePhone(raw: string | null | undefined): string | null {
  if (!raw) return null;

  const digits = raw.replace(/\D+/g, "");
  if (digits.length === 0) return null;

  // 8 (999) … и +7 (999) … — один и тот же номер. Ведущую восьмёрку меняем на
  // семёрку, а не отбрасываем: без кода страны номер станет десятизначным и
  // совпадёт с чужим кодом города.
  const withCountry =
    digits.length === RU_LENGTH && digits.startsWith("8") ? `7${digits.slice(1)}` : digits;

  // Десять цифр — номер без кода страны («9991234567»). Дописываем семёрку:
  // владелец вводит именно так чаще всего.
  const normalized = withCountry.length === RU_LENGTH - 1 ? `7${withCountry}` : withCountry;

  if (normalized.length !== RU_LENGTH) return null;
  // Российский мобильный/городской начинается с 7 после кода страны. Остальное
  // (казахстанские 77…, служебные короткие) в дедуп пускать нельзя: они либо
  // не наши, либо не номера.
  if (!normalized.startsWith("7")) return null;

  return normalized;
}

/** Человекочитаемый вид: +7 999 123-45-67. Для показа, не для сравнения. */
export function formatPhone(normalized: string | null | undefined): string | null {
  if (!normalized || normalized.length !== RU_LENGTH) return normalized ?? null;
  const d = normalized;
  return `+${d[0]} ${d.slice(1, 4)} ${d.slice(4, 7)}-${d.slice(7, 9)}-${d.slice(9)}`;
}
