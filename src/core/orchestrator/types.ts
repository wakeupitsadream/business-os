import type { z } from "zod";

/**
 * Инструмент агента: описание для модели + исполнитель + схема аргументов.
 *
 * Схема здесь не для красоты типов. Аргументы приходят от языковой модели —
 * то есть это недоверенный ввод, который выглядит структурированным. Модель
 * регулярно присылает число строкой, пропускает обязательное поле или
 * выдумывает лишнее; без валидации это доезжает до Prisma и падает где-то
 * глубоко, уже без связи с исходным запросом.
 */
export interface AgentTool<S extends z.ZodType = z.ZodType> {
  name: string;
  /** Описание для модели: от него зависит, вызовет ли она инструмент вовремя. */
  description: string;
  schema: S;

  /**
   * Опасные действия не исполняются сразу: агент лишь готовит их, а система
   * спрашивает владельца. Сюда попадает всё необратимое или направленное
   * наружу — отправка сообщения клиенту, удаление записей, трата денег.
   */
  dangerous?: boolean;

  /**
   * Поля аргументов, которые нельзя писать в журнал как есть (сохранятся
   * замаскированными). Журнал действий читается при разборе инцидентов, и
   * содержимое личных заметок там ни к чему.
   */
  sensitiveArgs?: string[];

  execute(args: z.infer<S>, ctx: ToolContext): Promise<ToolResult>;
}

export interface ToolContext {
  /** Запуск агента, в рамках которого вызван инструмент. */
  runId: string;
  /** Откуда пришёл запрос — влияет на источник создаваемых записей. */
  channel: "WEB" | "TELEGRAM";
  /** Момент начала запуска: все «сегодня» и «завтра» считаются от него. */
  now: Date;
}

export interface ToolResult {
  ok: boolean;
  /**
   * Что вернуть модели. Короткий человекочитаемый текст работает лучше JSON:
   * модель пересказывает его владельцу, а не зачитывает структуру.
   */
  message: string;
  /** Данные для журнала и интерфейса (в промпт не попадают). */
  data?: Record<string, unknown>;
}

export interface AgentRunOptions {
  agentKey: string;
  conversationId: string;
  channel: "WEB" | "TELEGRAM";
  trigger: "CHAT" | "TELEGRAM" | "CRON" | "MANUAL";
  /** Текст владельца. Уже сохранён в истории вызывающим кодом. */
  userText: string;
  now?: Date;
  signal?: AbortSignal;
}

export interface AgentRunResult {
  runId: string;
  text: string;
  /** Сколько раз модель вызывала инструменты — для журнала и отладки. */
  toolCallCount: number;
  /** Инструменты, потребовавшие подтверждения владельца. */
  pendingApprovals: string[];
  gateway?: string;
  model?: string;
}
