/**
 * Защита живых тестов от боевой базы.
 *
 * Живые тесты начинаются с `deleteMany({})` без единого условия — иначе их не
 * написать: проверяется как раз то, что моками не проверяется (уникальные
 * индексы, атомарность транзакции, суммы в базе). Базу они берут из
 * `DATABASE_URL`, а единственным гейтом была переменная `LIVE_DB=1`.
 *
 * То есть между «прогнать живые тесты» и «стереть все операции владельца»
 * стояло только то, какой `.env` оказался рядом. Резервных копий в системе нет,
 * восстановить было бы неоткуда.
 *
 * Здесь проверка хоста: местная база — можно, любая другая — падаем до первого
 * удаления. Разрешить неместную можно только явно, задав `TEST_DATABASE_URL`
 * ровно равной `DATABASE_URL`: случайно так не совпадёт, а осознанно — одна
 * строка.
 *
 * Сама строка подключения нигде не печатается, даже в сообщении об ошибке:
 * в ней пароль. Наружу идёт только имя хоста.
 */

/** Хосты, где база считается расходной: её не жалко стереть. */
const DISPOSABLE_HOSTS = new Set(["localhost", "127.0.0.1", "0.0.0.0", "::1", "[::1]", "db", "postgres"]);

/** Включены ли живые тесты вообще. */
export const liveDbEnabled = process.env.LIVE_DB === "1";

/**
 * Хост из строки подключения. `null`, если строки нет или она не разбирается —
 * оба случая трактуются как «непонятно куда», то есть небезопасно.
 *
 * Аргумент обязателен намеренно. Со значением по умолчанию явно переданный
 * `undefined` неотличим от «аргумент не передан», и функция молча подставляла
 * бы `process.env.DATABASE_URL`: проверка «строки нет» превращалась бы в
 * проверку окружения, в котором её запустили. На этом уже попался тест — в CI
 * переменная задана заглушкой на 127.0.0.1, и он падал ровно там, где локально
 * проходил.
 */
export function databaseHost(url: string | undefined): string | null {
  if (!url) return null;
  try {
    return new URL(url).hostname || null;
  } catch {
    return null;
  }
}

export function isDisposableDatabase(url: string | undefined): boolean {
  const explicit = process.env.TEST_DATABASE_URL;
  if (explicit && url && explicit === url) return true;
  const host = databaseHost(url);
  return host !== null && DISPOSABLE_HOSTS.has(host);
}

/**
 * Вызывать ПЕРВОЙ строкой в `beforeAll` любого теста, который чистит таблицы.
 * Падает до того, как что-нибудь удалится.
 */
export function assertDisposableDatabase(url: string | undefined = process.env.DATABASE_URL): void {
  if (isDisposableDatabase(url)) return;

  const host = databaseHost(url) ?? "не удалось разобрать DATABASE_URL";
  throw new Error(
    `Живые тесты стирают таблицы целиком, а база не выглядит расходной: хост «${host}».\n` +
      `Поднимите местный PostgreSQL и укажите его в DATABASE_URL, либо, если база всё-таки ` +
      `предназначена для тестов, продублируйте её строку в TEST_DATABASE_URL.`,
  );
}
