import { describe, expect, it } from "vitest";
import { GREETING } from "./handle";
import { secretaryRegistry } from "@/modules/secretary/agent";

/**
 * Приветствие устаревает бесшумно.
 *
 * Оно писалось, когда Ася действительно ничего не умела, и честно обещало
 * «скоро научусь вести задачи и считать деньги». Задачи, напоминания и финансы
 * появились — а текст остался, и владелец полгода читал бы, что этого нет.
 * Ошибка не ломает ни одного теста и не видна в логах: система работает, ею
 * просто не пользуются.
 */

describe("приветствие", () => {
  it("не обещает того, что уже сделано", () => {
    // Именно эти обороты и протухают. Появился инструмент — правь текст, а не
    // добавляй сюда исключение.
    for (const promise of ["скоро научусь", "пока не умею", "появится в ближайшем", "умею немного"]) {
      expect(GREETING.toLowerCase()).not.toContain(promise);
    }
  });

  it("показывает, чем система занимается на самом деле", () => {
    // Не список функций, а слова, по которым владелец узнает свои сценарии.
    for (const capability of ["задач", "напомн", "расход"]) {
      expect(GREETING.toLowerCase()).toContain(capability);
    }
  });

  it("упоминает /ping — единственную команду, которая есть", () => {
    expect(GREETING).toContain("/ping");
  });

  it("влезает в одно сообщение Telegram", () => {
    expect(GREETING.length).toBeLessThan(4096);
  });

  it("инструменты у секретаря действительно есть", () => {
    // Обратная сторона: если реестр однажды опустеет, приветствие станет враньём
    // в другую сторону, и об этом лучше узнать здесь.
    expect(secretaryRegistry.names().length).toBeGreaterThan(0);
  });
});
