/**
 * Коэффициенты модели времени.
 *
 * Числа взяты из брифа по «Сытому Япоше» (раздел «Что нужно для работы системы
 * загрузки») и на старте являются обоснованными оценками, а не измерениями.
 * После запуска обещанное время логируется рядом с фактическим, и раз в две
 * недели коэффициенты подгоняются — только тогда можно говорить владельцу
 * «попадаем в интервал в N% случаев».
 *
 * Держать их в одном файле — намеренно: калибровка не должна превращаться в
 * поиск магических чисел по всему движку.
 */

export const CALIBRATION = {
  /** Базовое время сборки заказа на незагруженной кухне, минуты. */
  cookBaseMin: 24,

  /**
   * Полный круг курьера: доехать, отдать, вернуться. Минуты.
   * В брифе — 24–28, берём середину.
   */
  courierRoundTripMin: 26,

  /** Сколько заказов курьер увозит за один выезд. */
  ordersPerCourierTrip: 2,

  /** Средняя скорость по городу, км/ч. */
  citySpeedKmh: 24,

  /**
   * Поправка на то, что по улицам едут не по прямой.
   *
   * Расстояние считается по большому кругу, реальный пробег всегда длиннее.
   * 1.35 — обычная оценка для городской сетки; уточняется калибровкой.
   */
  detourFactor: 1.35,

  /** Передача заказа курьеру и подъём к двери, минуты. */
  handoffMin: 4,

  /**
   * После скольки минут молчания счётчики считаются протухшими.
   *
   * Ровно та страховка из брифа: если на кассе забыли обновить загрузку,
   * система молча переходит на оценку по времени суток и помечает время
   * ориентировочным. Клиент никогда не видит пустоту.
   */
  stalenessMin: 40,

  /** Нижняя граница обещанного интервала относительно оценки, минуты. */
  promiseLowerSlackMin: 5,

  /** Верхняя граница обещанного интервала относительно оценки, минуты. */
  promiseUpperSlackMin: 10,

  /** Интервал округляется до кратности, минуты. */
  promiseRoundToMin: 5,

  /**
   * Минимальное обещание, минуты.
   *
   * Даже при пустой кухне и свободном курьере «через 10 минут» — обещание,
   * которое невозможно выполнить, и оно бьёт по доверию сильнее, чем честные
   * сорок минут.
   */
  promiseFloorMin: 35,
} as const;

export type Calibration = typeof CALIBRATION;
