import type { BrandId, KitchenId, LoadSnapshot } from "../types";

/**
 * Задел под iiko.
 *
 * У владельца стоит iiko — это единственный из «звёздочных» вопросов брифа,
 * на который ответ уже есть. Но ключей и доступа к их облаку у нас нет, и
 * писать вслепую боевой клиент бессмысленно: непроверяемый код, который
 * выглядит рабочим, хуже честной заглушки.
 *
 * Поэтому здесь зафиксирован КОНТРАКТ — то, что система хочет от учётной
 * системы. Реализаций две: мок на демо-данных и, когда дадут доступ, клиент
 * iiko Cloud API. Движок между ними не различает: он видит только этот
 * интерфейс.
 *
 * Такая граница ещё и страхует от привязки к вендору: если завтра окажется
 * Frontpad или r_keeper, меняется одна реализация, а не весь диспетчер.
 */
export interface KitchenLoadSource {
  /** Человеку понятное имя источника — уходит в интерфейс и в логи. */
  readonly name: string;

  /**
   * Текущая загрузка всех кухонь.
   *
   * Возвращает срезы с временем снятия: движок сам решит, протухли они или
   * нет. Источник НЕ обязан гарантировать свежесть — он обязан честно
   * сказать, когда данные сняты.
   */
  loadSnapshots(): Promise<readonly LoadSnapshot[]>;

  /**
   * Стоп-лист: что сейчас нельзя заказать.
   *
   * В iiko это живая величина, и она — самая недооценённая часть интеграции.
   * Заказ, принятый на позицию, которой нет, стоит дороже любого опоздания:
   * оператор звонит, извиняется, клиент отменяет.
   */
  stopList(): Promise<ReadonlySet<string>>;
}

/** Заказ, отдаваемый в учётную систему. */
export type OutboundOrder = {
  readonly kitchenId: KitchenId;
  readonly brandId: BrandId;
  readonly lines: readonly {
    readonly sku: string;
    readonly qty: number;
  }[];
  readonly address: string;
  readonly phone: string;
  readonly comment: string;
  /** Ключ идемпотентности: повтор с тем же ключом не создаёт второй заказ. */
  readonly idempotencyKey: string;
};

/**
 * Приём заказов учётной системой.
 *
 * Отделено от чтения загрузки намеренно: читать можно с первого дня, а писать
 * заказы в боевую iiko — шаг, который владелец должен разрешить отдельно.
 * Пока разрешения нет, работает `loadSource` без `orderSink`, и заказы уходят
 * оператору в Telegram, как в эталонном демо.
 */
export interface OrderSink {
  readonly name: string;

  /**
   * Передать заказ. Реализация ОБЯЗАНА быть идемпотентной по
   * `idempotencyKey`.
   *
   * Причина та же, что в вебхуках Telegram у business-os: таймаут не означает
   * недоставку. Повтор без ключа — это второй заказ на той же кухне, то есть
   * выброшенные продукты и разбирательство с клиентом.
   */
  push(order: OutboundOrder): Promise<{ readonly externalId: string }>;
}
