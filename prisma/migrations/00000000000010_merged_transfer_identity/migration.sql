-- Вторая личность операции, сведённой в перевод из двух выписок.
--
-- Перевод между своими счетами приходит ДВУМЯ строками — по одной в выписке
-- каждого счёта, — а хранится одной операцией. До сих пор она несла ключ дедупа
-- только одной из выписок: строка второй выписки не записывалась вовсе, и её
-- ключ не сохранялся нигде. Повторный импорт пересекающегося периода не находил
-- её и создавал заново — те же деньги второй раз.
--
-- Колонки nullable и без обратного заполнения: у уже сведённых переводов второй
-- ключ восстановить неоткуда (строка, из которой их свели, не сохранилась).
-- Это честно означает «про эти переводы мы второго следа не знаем» — хуже, чем
-- знать, но лучше, чем выдумать.
ALTER TABLE "Transaction" ADD COLUMN IF NOT EXISTS "mergedAccountId" TEXT;
ALTER TABLE "Transaction" ADD COLUMN IF NOT EXISTS "mergedDedupKey" TEXT;

CREATE INDEX IF NOT EXISTS "Transaction_mergedAccountId_mergedDedupKey_idx"
  ON "Transaction"("mergedAccountId", "mergedDedupKey");
