-- Расширения PostgreSQL. Имя каталога начинается с нулей намеренно: Prisma
-- применяет миграции в лексикографическом порядке, а колонка
-- MemoryFact.embedding имеет тип vector(1536) — без расширения `vector`
-- миграция схемы упадёт с "type vector does not exist".
--
-- Обе команды идемпотентны: миграции на проде гонятся на каждом старте
-- контейнера, а на Neon расширение обычно уже включено руками из SQL-консоли
-- (см. README, раздел «Быстрый старт»).

CREATE EXTENSION IF NOT EXISTS vector;

-- pg_trgm понадобится в Фазе 3 для нечёткого дедупа лидов (похожие названия
-- компаний, опечатки в адресах). Включаем сразу: добавление расширения — это
-- DDL на всю БД, дешевле сделать один раз здесь, чем отдельной миграцией
-- в момент, когда лиды уже собираются.
CREATE EXTENSION IF NOT EXISTS pg_trgm;
