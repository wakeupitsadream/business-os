-- Полнотекстовый поиск по фактам памяти — запасной путь, когда векторный
-- недоступен.
--
-- Зачем он вообще. Векторный поиск зависит от того, что провайдер отдаёт
-- эмбеддинги. Если он их не отдаёт, отдаёт с перебоями или у конкретного факта
-- вектор не успел посчитаться, память перестаёт работать целиком — а вместе с
-- ней и половина смысла секретаря. Полнотекстовый поиск не требует ничего,
-- кроме самой базы, и находит по словам то, что вектор нашёл бы по смыслу.
--
-- Индекс по ВЫРАЖЕНИЮ, а не по отдельной колонке: генерируемую колонку
-- пришлось бы объявлять в schema.prisma как Unsupported и следить, чтобы
-- `migrate diff` не пересоздал её обычной. Здесь схема Prisma не меняется
-- вовсе, а запрос вида
--   WHERE to_tsvector('russian', text) @@ plainto_tsquery('russian', $1)
-- этим индексом пользуется.
CREATE INDEX IF NOT EXISTS "MemoryFact_text_fts_idx"
  ON "MemoryFact" USING gin (to_tsvector('russian', "text"));

-- Отдельного триграммного индекса здесь нет намеренно. Второй ярус отката
-- ищет через word_similarity() с явным порогом, а такой запрос GIN-индексом
-- не пользуется (для этого нужен оператор <% и настройка порога на уровне
-- сессии, которую не задать через пул соединений). Фактов о владельце — сотни,
-- последовательный просмотр по ним дешевле мёртвого индекса, который
-- сбивает с толку при чтении схемы. Расширение pg_trgm при этом нужно: из
-- него берётся сама функция word_similarity.
