-- Ключ строки выписки, сведённой в перевод.
--
-- Раньше он не сохранялся нигде: строка выписки не записывалась (её роль
-- играет уцелевшая встречная операция), а своя dedupKey у той занята
-- собственным ключом. Повторный импорт пересекающегося периода — обычное дело
-- в конце месяца — не находил ключ, не находил и кандидата на сведение
-- (встречная уже TRANSFER и отфильтрована), и записывал те же деньги заново.
--
-- Номер 17, а не 12: 12–16 заняты стопкой продаж, и одинаковые префиксы у
-- независимых миграций сбивают с толку при чтении каталога.
ALTER TABLE "Transaction" ADD COLUMN "mergedDedupKey" TEXT;
CREATE UNIQUE INDEX "Transaction_mergedDedupKey_key" ON "Transaction"("mergedDedupKey");
