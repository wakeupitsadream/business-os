-- Индекс приближённого поиска ближайших соседей по векторной памяти.
--
-- Prisma не умеет описывать индексы pgvector в schema.prisma (колонка объявлена
-- как Unsupported), поэтому индекс живёт отдельной ручной миграцией. Она
-- намеренно не входит в файл, сгенерированный `prisma migrate diff`: тот файл
-- перегенерируется при изменениях схемы, и ручная правка в нём была бы
-- потеряна при первой же регенерации.
--
-- hnsw + vector_cosine_ops — под оператор `<=>` (косинусное расстояние),
-- которым ищет модуль памяти. Без индекса поиск деградирует в полный перебор:
-- на сотне фактов это незаметно, на десятках тысяч — секунды на КАЖДОЕ
-- сообщение секретарю.
CREATE INDEX IF NOT EXISTS "MemoryFact_embedding_hnsw_idx"
  ON "MemoryFact" USING hnsw ("embedding" vector_cosine_ops);
