-- Повтор недоставленного напоминания.
--
-- Расписание сдвигается ДО отправки — иначе падение после отправки давало бы
-- одно и то же напоминание раз в минуту до конца времён. Но обратная сторона
-- этого порядка до сих пор ничем не подбиралась: блип Telegram на одну минуту
-- уничтожал напоминание совсем, и владелец узнавал об этом только по тому,
-- что его не разбудили.
--
-- `retryOf` хранит НАСТОЯЩИЙ срок, а не время повтора: иначе серия
-- повторяющегося напоминания уезжала бы на две минуты при каждой неудаче.
-- AlterTable
ALTER TABLE "Reminder" ADD COLUMN     "deliveryAttempts" INTEGER NOT NULL DEFAULT 0,
ADD COLUMN     "retryOf" TIMESTAMP(3);

