-- Повторная попытка доставки напоминания.
--
-- Порядок «сдвинуть расписание, потом отправить» выбран сознательно: дубль раз
-- в минуту хуже одной потери. Но потерю никто не подбирал — блип Telegram
-- уничтожал напоминание совсем, а владелец узнавал об этом только по тому, что
-- его не разбудили.
--
-- deliveryAttempts — счётчик неудач подряд, обнуляется успешной отправкой.
-- retryOf — время, на которое напоминание было назначено по-настоящему, пока
-- nextFireAt временно сдвинут ради повтора. Без него серия повторяющегося
-- напоминания уезжала бы на две минуты вперёд при каждой неудаче: следующее
-- срабатывание считается ОТ ПРЕДЫДУЩЕГО, а не от «сейчас», — специально, чтобы
-- опоздавшая доставка не сдвигала расписание.
ALTER TABLE "Reminder" ADD COLUMN IF NOT EXISTS "deliveryAttempts" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "Reminder" ADD COLUMN IF NOT EXISTS "retryOf" TIMESTAMP(3);
