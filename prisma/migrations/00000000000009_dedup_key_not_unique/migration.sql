-- Ключ дедупа перестаёт быть уникальным.
--
-- Две одинаковые операции одного дня на одном счёте — законная пара (две чашки
-- кофе по 200 ₽), и различить их нечем: у них совпадает всё, из чего строится
-- ключ. Уникальный индекс утверждал, что такого не бывает, и вторая строка
-- выписки молча не импортировалась — владелец видел только счётчик «Дублей: 1»
-- и не мог проверить, что за ним стоит.
--
-- Инвариант «повторный импорт того же файла не создаёт новых строк» никуда не
-- делся, он просто переехал из индекса в код: classifyRows считает, сколько
-- строк с этим ключом уже лежит в базе, и ровно столько первых строк файла
-- помечает дублями.
--
-- Миграция безопасна в обе стороны: снятие ограничения не может упасть на
-- существующих данных, а обычный индекс по той же паре колонок оставляет
-- запросы дедупа такими же быстрыми.
DROP INDEX IF EXISTS "Transaction_accountId_dedupKey_key";
CREATE INDEX IF NOT EXISTS "Transaction_accountId_dedupKey_idx"
  ON "Transaction"("accountId", "dedupKey");
