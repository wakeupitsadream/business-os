-- Пояс владельца: Москва → Екатеринбург.
--
-- Строка Settings создаётся лениво при первом обращении, и на первом запуске
-- в неё лёг тогдашний дефолт — Europe/Moscow. Константа в коде теперь другая,
-- но эту строку она не перепишет: getOwnerTimezone() читает базу, и по ней
-- считаются сроки ПОВТОРЯЮЩИХСЯ напоминаний. Без этой миграции ежедневное
-- напоминание «в 9 утра» приходило бы в 7:00 по местному времени.
--
-- Условие на Europe/Moscow намеренно: если пояс когда-нибудь начнут менять
-- осознанно, повторный прогон миграции не затрёт сделанный выбор.

UPDATE "Settings"
SET timezone = 'Asia/Yekaterinburg'
WHERE timezone = 'Europe/Moscow';
